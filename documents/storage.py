"""
Secure handling of uploaded documents.

Security checks applied to every upload:
    1. Extension must be .pdf
    2. Size must be > 0 and <= MAX_UPLOAD_MB
    3. Content must start with the PDF magic bytes "%PDF-" (extension alone is not trusted)
    4. PyMuPDF must be able to open it, it must not be encrypted, and it must have pages
    5. The stored file name is generated by us (UUID prefix + sanitised name), so a
       malicious name such as "../../etc/passwd.pdf" can never escape the upload folder.
"""

from __future__ import annotations

import hashlib
import re
import uuid
from dataclasses import dataclass
from pathlib import Path

import pymupdf

from app.config import settings

ALLOWED_EXTENSIONS = {".pdf"}
PDF_MAGIC = b"%PDF-"
_SAFE_CHARS = re.compile(r"[^A-Za-z0-9._-]+")


class DocumentValidationError(ValueError):
    """Raised when an uploaded file fails a safety check (message is user-safe)."""


@dataclass(frozen=True)
class StoredFile:
    original_filename: str
    stored_filename: str
    file_path: Path
    file_size_bytes: int
    sha256: str
    page_count: int


def safe_filename(name: str, max_length: int = 120) -> str:
    """Strip directories and unsafe characters: '../My Bill (1).pdf' -> 'My_Bill_1_.pdf'."""
    base = Path(name.replace("\\", "/")).name  # drop any path component (Windows or POSIX)
    stem, suffix = Path(base).stem, Path(base).suffix.lower()
    stem = _SAFE_CHARS.sub("_", stem).strip("._") or "document"
    return f"{stem[: max_length - len(suffix)]}{suffix}"


def sha256_bytes(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def validate_pdf_bytes(data: bytes, filename: str, max_bytes: int | None = None) -> int:
    """Validate an uploaded PDF and return its page count."""
    max_bytes = max_bytes or settings.max_upload_bytes
    if Path(filename).suffix.lower() not in ALLOWED_EXTENSIONS:
        raise DocumentValidationError(f"'{filename}': only PDF files are accepted.")
    if not data:
        raise DocumentValidationError(f"'{filename}' is empty.")
    if len(data) > max_bytes:
        raise DocumentValidationError(
            f"'{filename}' is {len(data) / 1_048_576:.1f} MB; the limit is {max_bytes / 1_048_576:.0f} MB."
        )
    if not data.startswith(PDF_MAGIC):
        raise DocumentValidationError(f"'{filename}' is not a valid PDF (file signature mismatch).")
    try:
        with pymupdf.open(stream=data, filetype="pdf") as doc:
            if doc.needs_pass or doc.is_encrypted:
                raise DocumentValidationError(f"'{filename}' is password-protected.")
            if doc.page_count == 0:
                raise DocumentValidationError(f"'{filename}' has no pages.")
            return doc.page_count
    except DocumentValidationError:
        raise
    except Exception as exc:  # corrupt / unreadable PDF
        raise DocumentValidationError(f"'{filename}' could not be read as a PDF.") from exc


def claim_folder(claim_number: str, base_dir: Path | None = None) -> Path:
    folder = (base_dir or settings.uploads_dir) / safe_filename(claim_number)
    folder.mkdir(parents=True, exist_ok=True)
    return folder


def store_claim_document(claim_number: str, filename: str, data: bytes,
                         base_dir: Path | None = None) -> StoredFile:
    """Validate and save an upload under data/uploads/<claim_number>/."""
    pages = validate_pdf_bytes(data, filename)
    clean = safe_filename(filename)
    stored = f"{uuid.uuid4().hex[:8]}_{clean}"
    path = claim_folder(claim_number, base_dir) / stored
    path.write_bytes(data)
    return StoredFile(filename, stored, path, len(data), sha256_bytes(data), pages)
